"""Trains the belt pickup correction model and writes scripts/pickup_model.lua.

Input: RESULT lines produced by the itt-harness mod (belt -> chest cases, fully compressed input belt).
Target: log(measured cycle / physics cycle), physics cycle = 2*H + (k-1)*max(1, 0.2/ext).
"""
import glob, json, math, re, sys
import numpy as np
from sklearn.ensemble import GradientBoostingRegressor

ITEM_SPACING = 0.25
PICKUP_REACH = 0.2
BELT_SPEED = {"transport-belt": 0.03125, "fast-transport-belt": 0.0625,
              "express-transport-belt": 0.09375, "turbo-transport-belt": 0.125}
FEATURES = ["half_swing", "log_rotation", "log_extension", "radius", "belt_speed", "pickups", "lanes", "stack",
            "belt_over_extension", "belt_over_tangential", "supply_interval_over_step", "physics_pickup", "supply_pickup"]

def features(H, rot, ext, r, v, k, lanes, ss):
    step = max(1.0, PICKUP_REACH / ext)
    tangential = 2 * math.pi * r * rot
    return [H, math.log(rot), math.log(ext), r, v, k, lanes, ss,
            v / ext, v / tangential,
            ITEM_SPACING / (lanes * v) / step,
            (k - 1) * step,
            (k - 1) * ITEM_SPACING / (lanes * v)]

def physics_cycle(H, ext, k):
    return 2 * H + (k - 1) * max(1.0, PICKUP_REACH / ext)

def load(files, radius):
    rows = []
    for f in files:
        for line in open(f):
            if "RESULT " not in line:
                continue
            d = json.loads(line.split("RESULT ", 1)[1])
            c = d.get("case")
            if not c or c.get("src") != "belt" or c.get("dst") != "chest" or d["rate"] <= 0:
                continue
            v = BELT_SPEED[c["srcbelt"]]
            ss = d["pstack"]
            lanes = 1 if c.get("lanes") == "left" else 2
            n = d["pitems"]
            k = math.ceil(n / ss)
            if d["rate"] >= 0.97 * lanes * v / ITEM_SPACING * ss * 60:
                continue  # limited by belt supply, cycle not observable
            H, rot, ext = d["phalf"], d["rot"], d["ext"]
            r = radius.get(c["ins"], 1)
            rows.append((features(H, rot, ext, r, v, k, lanes, ss), physics_cycle(H, ext, k), n * 60 / d["rate"]))
    return rows

def lua_number(x):
    return repr(float("%.7g" % x))

def export(model, path):
    out = ["-- Generated by train_pickup_model.py from Factorio 2.1.22 measurements. Do not edit by hand.",
           "-- Gradient boosted trees predicting log(measured cycle / physics cycle) for belt pickups.",
           "-- Nodes: feature index (0 = leaf), threshold, left child, right child, value.",
           "return {",
           "  base = %s," % lua_number(model.init_.constant_[0][0]),
           "  rate = %s," % lua_number(model.learning_rate),
           "  trees = {"]
    for estimator in model.estimators_[:, 0]:
        t = estimator.tree_
        feature = [0 if t.children_left[i] == -1 else t.feature[i] + 1 for i in range(t.node_count)]
        threshold = [0 if feature[i] == 0 else t.threshold[i] for i in range(t.node_count)]
        left = [0 if feature[i] == 0 else t.children_left[i] + 1 for i in range(t.node_count)]
        right = [0 if feature[i] == 0 else t.children_right[i] + 1 for i in range(t.node_count)]
        value = [t.value[i][0][0] if feature[i] == 0 else 0 for i in range(t.node_count)]
        out.append("    {f={%s},t={%s},l={%s},r={%s},v={%s}}," % (
            ",".join(map(str, feature)), ",".join(lua_number(x) for x in threshold),
            ",".join(map(str, left)), ",".join(map(str, right)), ",".join(lua_number(x) for x in value)))
    out += ["  },", "}", ""]
    open(path, "w").write("\n".join(out))

if __name__ == "__main__":
    results_dir, protos_dir, output = sys.argv[1], sys.argv[2], sys.argv[3]
    radius = {"long-handed-inserter": 2}
    for f in glob.glob(protos_dir + "/protos*.lua"):
        for m in re.finditer(r'name="([^"]+)",rot=[\d.]+,ext=[\d.]+,r=(\d)', open(f).read()):
            radius[m.group(1)] = int(m.group(2))
    rows = load(sorted(glob.glob(results_dir + "/out_ml*.txt")) + sorted(glob.glob(results_dir + "/out_vt*.txt")), radius)
    X = np.array([r[0] for r in rows])
    y = np.log(np.array([r[2] / r[1] for r in rows]))
    model = GradientBoostingRegressor(max_depth=5, n_estimators=150, learning_rate=0.1, subsample=0.8, random_state=0)
    model.fit(X, y)
    pred = np.array([r[1] for r in rows]) * np.exp(model.predict(X))
    err = np.abs(np.array([r[2] for r in rows]) / pred - 1)
    print("samples", len(rows), "train mean|err| %.2f%%" % (err.mean() * 100))
    export(model, output)
